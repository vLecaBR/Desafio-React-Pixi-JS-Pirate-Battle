#!/usr/bin/env node
/**
 * Aggregates the profiling results in docs/profiling/*.json into
 * docs/profiling/REPORT.md (tables for frame rate, frame times, entities and memory).
 *
 * Usage: npm run perf:report
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'docs/profiling');
const files = readdirSync(dir)
  .filter((file) => file.endsWith('.json'))
  .sort();

const lines = [
  '# Profiling results',
  '',
  'Generated by `npm run perf:report` from the JSON files in this folder.',
  'See [../PROFILING.md](../PROFILING.md) for the method and the analysis.',
  '',
];

for (const file of files) {
  const data = JSON.parse(readFileSync(path.join(dir, file), 'utf8'));
  const env = data.environment ?? {};
  lines.push(`## ${file}`, '');
  lines.push(
    `- Date: ${env.date ?? '?'}`,
    `- Browser: ${env.browser ?? '?'} (headless${env.softwareGl ? ', software GL' : ', hardware GPU'})`,
    `- WebGL renderer: ${env.webglRenderer ?? '?'}`,
    `- OS / CPU / RAM: ${env.os ?? '?'} / ${env.cpu ?? '?'} / ${env.memoryGb ?? '?'} GB`,
    `- Viewport: ${env.viewport?.width ?? '?'} × ${env.viewport?.height ?? '?'} @ DPR ${env.devicePixelRatio ?? '?'}`,
    `- Configuration: \`${JSON.stringify(data.config)}\``,
    '',
  );

  if (data.kind === 'three-minute-match') {
    const r = data.report;
    lines.push(
      '| Metric | Value |',
      '| --- | ---: |',
      `| Duration | ${r.durationSec} s (${r.frames} frames) |`,
      `| Average FPS | ${r.avgFps} |`,
      `| Frame time avg / p50 / p95 / p99 / max (ms) | ${r.frameMs.avg} / ${r.frameMs.p50} / ${r.frameMs.p95} / ${r.frameMs.p99} / ${r.frameMs.max} |`,
      `| Update (CPU) avg / p95 / max (ms) | ${r.updateMs.avg} / ${r.updateMs.p95} / ${r.updateMs.max} |`,
      `| Frames over 25 ms / 33.3 ms | ${r.framesOver.ms25 ?? r.framesOver.ms16_7} / ${r.framesOver.ms33_3} |`,
      `| Ships avg / max | ${r.entities.ships.avg} / ${r.entities.ships.max} |`,
      `| Projectiles avg / max | ${r.entities.projectiles.avg} / ${r.entities.projectiles.max} |`,
      `| Effects avg / max | ${r.entities.effects.avg} / ${r.entities.effects.max} |`,
      `| Display objects avg / max | ${r.entities.displayObjects.avg} / ${r.entities.displayObjects.max} |`,
      `| JS heap at the end | ${r.heapUsedMb ?? '?'} MB |`,
      `| Match | ${data.match ? `${data.match.phase}, ${data.match.elapsedMs} ms, score ${data.match.score}, ${data.match.spawnsSoFar} spawns` : '?'} |`,
      '',
    );
  } else if (data.kind === 'memory-cycles') {
    lines.push(
      '| Cycle | JS heap used (MB) | JS heap total (MB) | DOM nodes | Listeners | Documents | Canvases |',
      '| ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
      ...data.results.map(
        (m) =>
          `| ${m.cycle === 0 ? '0 (before)' : m.cycle} | ${m.jsHeapUsedMb} | ${m.jsHeapTotalMb} | ${m.domNodes} | ${m.jsEventListeners} | ${m.documents} | ${m.canvases} |`,
      ),
      '',
    );
  }
}

writeFileSync(path.join(dir, 'REPORT.md'), `${lines.join('\n')}\n`);
console.log(`Wrote docs/profiling/REPORT.md from ${files.length} result file(s).`);
