import { z } from 'zod';
import { readStored, STORAGE_KEYS, writeStored } from '../../persistence/storage.ts';

export const SOUND_IDS = [
  'cannon_broadside',
  'cannon_fire_1',
  'cannon_fire_2',
  'cannon_fire_3',
  'cannonball_water_hit_1',
  'cannonball_water_hit_2',
  'game_complete',
  'game_over',
  'game_pause',
  'game_resume',
  'game_start',
  'health_low',
  'ocean_ambience_loop',
  'score_point',
  'ship_collision',
  'ship_explosion_1',
  'ship_explosion_2',
  'ship_sailing_loop',
  'ship_sinking',
  'ship_wood_hit_1',
  'ship_wood_hit_2',
  'time_warning',
  'ui_back',
  'ui_click',
  'ui_close',
  'ui_hover',
  'ui_open',
] as const;

export type SoundId = (typeof SOUND_IDS)[number];
export type LoopId = 'ocean_ambience_loop' | 'ship_sailing_loop';

const audioPrefsSchema = z.object({ muted: z.boolean() });

/** Identical sounds closer than this are merged (e.g. three broadside hits). */
const MIN_REPEAT_MS = 45;

interface Loop {
  readonly source: AudioBufferSourceNode;
  readonly gain: GainNode;
}

/**
 * Web Audio sound effects and ambience loops.
 *
 * - The AudioContext is only created on the first user gesture (browser autoplay
 *   rules), so nothing plays or warns before the player interacts.
 * - Files are the compressed variants generated by `npm run assets:audio`
 *   (OGG Vorbis, or AAC/M4A where Vorbis is unsupported), decoded once and cached.
 * - Audio is optional: any failure (unsupported, network, decode) is silent and
 *   never affects the game.
 * - Mute is persisted locally.
 */
export class AudioManager {
  private context: AudioContext | null = null;
  private master: GainNode | null = null;
  private loopBus: GainNode | null = null;
  private readonly buffers = new Map<SoundId, AudioBuffer>();
  private readonly pending = new Map<SoundId, Promise<AudioBuffer | null>>();
  private readonly queued = new Set<SoundId>();
  private readonly loops = new Map<LoopId, Loop>();
  private readonly wantedLoops = new Map<LoopId, number>();
  private readonly lastPlayed = new Map<SoundId, number>();
  private readonly listeners = new Set<() => void>();
  private mutedState: boolean;
  private loopsSuspended = false;
  private unlockInstalled = false;

  constructor() {
    this.mutedState =
      typeof window === 'undefined'
        ? true
        : (readStored(STORAGE_KEYS.audio, audioPrefsSchema)?.muted ?? false);
  }

  get muted(): boolean {
    return this.mutedState;
  }

  setMuted(muted: boolean): void {
    this.mutedState = muted;
    writeStored(STORAGE_KEYS.audio, { muted });
    if (this.master && this.context) {
      this.master.gain.setTargetAtTime(muted ? 0 : 1, this.context.currentTime, 0.02);
    }
    for (const listener of this.listeners) listener();
  }

  /** Subscribe to mute changes (for React). */
  subscribe(listener: () => void): () => void {
    this.listeners.add(listener);
    return () => {
      this.listeners.delete(listener);
    };
  }

  /** Creates/resumes the AudioContext on the first pointer or key press. */
  installUnlock(): void {
    if (this.unlockInstalled || typeof window === 'undefined') return;
    this.unlockInstalled = true;
    const unlock = () => {
      if (!this.createContext()) return;
      window.removeEventListener('pointerdown', unlock, true);
      window.removeEventListener('keydown', unlock, true);
      for (const id of this.queued) void this.load(id);
      this.queued.clear();
      for (const [id, volume] of this.wantedLoops) this.startLoop(id, volume);
    };
    window.addEventListener('pointerdown', unlock, true);
    window.addEventListener('keydown', unlock, true);
  }

  /** Decodes the given sounds in the background (after unlock; failures ignored). */
  preload(ids: readonly SoundId[]): void {
    for (const id of ids) {
      if (this.context) void this.load(id);
      else this.queued.add(id);
    }
  }

  play(id: SoundId, options: { volume?: number; rate?: number } = {}): void {
    const context = this.activeContext();
    if (!context || !this.master || this.mutedState) return;
    const buffer = this.buffers.get(id);
    if (!buffer) {
      void this.load(id);
      return;
    }
    const now = performance.now();
    if (now - (this.lastPlayed.get(id) ?? -Infinity) < MIN_REPEAT_MS) return;
    this.lastPlayed.set(id, now);

    const source = context.createBufferSource();
    source.buffer = buffer;
    source.playbackRate.value = options.rate ?? 1;
    const gain = context.createGain();
    gain.gain.value = options.volume ?? 1;
    source.connect(gain).connect(this.master);
    source.addEventListener('ended', () => {
      source.disconnect();
      gain.disconnect();
    });
    source.start();
  }

  /** Starts a loop (or remembers it until audio is unlocked and decoded). */
  startLoop(id: LoopId, volume: number): void {
    this.wantedLoops.set(id, volume);
    const context = this.activeContext();
    if (!context || !this.loopBus || this.loops.has(id)) return;
    const buffer = this.buffers.get(id);
    if (!buffer) {
      void this.load(id).then((loaded) => {
        const wanted = this.wantedLoops.get(id);
        if (loaded && wanted !== undefined && !this.loops.has(id)) this.startLoop(id, wanted);
      });
      return;
    }
    const source = context.createBufferSource();
    source.buffer = buffer;
    source.loop = true;
    const gain = context.createGain();
    gain.gain.value = volume;
    source.connect(gain).connect(this.loopBus);
    source.start();
    this.loops.set(id, { source, gain });
  }

  setLoopVolume(id: LoopId, volume: number): void {
    if (this.wantedLoops.has(id)) this.wantedLoops.set(id, volume);
    const loop = this.loops.get(id);
    if (!loop || !this.context) return;
    loop.gain.gain.setTargetAtTime(volume, this.context.currentTime, 0.15);
  }

  /** Silences (or restores) every loop, e.g. while the match is paused. */
  setLoopsSuspended(suspended: boolean): void {
    this.loopsSuspended = suspended;
    if (!this.loopBus || !this.context) return;
    this.loopBus.gain.setTargetAtTime(suspended ? 0 : 1, this.context.currentTime, 0.05);
  }

  stopLoop(id: LoopId): void {
    this.wantedLoops.delete(id);
    const loop = this.loops.get(id);
    if (!loop) return;
    this.loops.delete(id);
    try {
      loop.source.stop();
    } catch {
      // Already stopped.
    }
    loop.source.disconnect();
    loop.gain.disconnect();
  }

  stopAllLoops(): void {
    for (const id of new Set([...this.loops.keys(), ...this.wantedLoops.keys()])) {
      this.stopLoop(id);
    }
    this.setLoopsSuspended(false);
  }

  private activeContext(): AudioContext | null {
    const context = this.context;
    if (context?.state === 'suspended') void context.resume().catch(() => undefined);
    return context;
  }

  private createContext(): boolean {
    if (typeof AudioContext === 'undefined') return false;
    if (!this.context) {
      try {
        this.context = new AudioContext();
        this.master = this.context.createGain();
        this.master.gain.value = this.mutedState ? 0 : 1;
        this.master.connect(this.context.destination);
        this.loopBus = this.context.createGain();
        this.loopBus.gain.value = this.loopsSuspended ? 0 : 1;
        this.loopBus.connect(this.master);
      } catch {
        return false;
      }
    }
    if (this.context.state === 'suspended') void this.context.resume().catch(() => undefined);
    return true;
  }

  private load(id: SoundId): Promise<AudioBuffer | null> {
    const cached = this.buffers.get(id);
    if (cached) return Promise.resolve(cached);
    const inflight = this.pending.get(id);
    if (inflight) return inflight;
    const context = this.context;
    if (!context) {
      this.queued.add(id);
      return Promise.resolve(null);
    }

    const promise = fetch(`/assets/generated/sounds/${id}.${preferredFormat()}`)
      .then((response) => (response.ok ? response.arrayBuffer() : Promise.reject(new Error())))
      .then((data) => context.decodeAudioData(data))
      .then((buffer) => {
        this.buffers.set(id, buffer);
        return buffer;
      })
      .catch(() => null)
      .finally(() => {
        this.pending.delete(id);
      });
    this.pending.set(id, promise);
    return promise;
  }
}

let format: 'ogg' | 'm4a' | null = null;

function preferredFormat(): 'ogg' | 'm4a' {
  if (!format) {
    const probe = document.createElement('audio');
    format = probe.canPlayType('audio/ogg; codecs="vorbis"') !== '' ? 'ogg' : 'm4a';
  }
  return format;
}

/** Shared instance: sounds are decoded once for the whole session. */
export const audio = new AudioManager();
